"""Build docs/results/README.md - one table over every results file, so the comparison reads at a glance.

Run: PYTHONPATH=. .venv/bin/python eval/summarize.py
"""
import re
from pathlib import Path

RESULTS = Path(__file__).resolve().parent.parent / "docs" / "results"

# (file, what it shows) in reading order; files that don't exist yet are skipped.
ROWS = [
    ("report.md", "Report mode on the GPO 2018 Annual Report"),
    ("standard-on-gpo.md", "Standard mode on the same GPO report"),
    ("long.md", "Long document mode on the World Bank GEP, June 2026"),
    ("visual.md", "Visual document mode on the iMac environmental report"),
    ("standard-on-imac.md", "Standard mode on the same iMac report"),
]


def summarize(path: Path) -> dict:
    text = path.read_text()
    document = re.search(r"^Document: `([^`]+)` \((\d+) chunks", text, re.M)
    headline = re.search(r"^\*\*(.+)\*\*$", text, re.M)
    return {
        "document": document.group(1) if document else "?",
        "chunks": document.group(2) if document else "?",
        "headline": headline.group(1) if headline else "?",
    }


def build() -> str:
    lines = [
        "# Evaluation results",
        "",
        "Generated by `eval/summarize.py` from the files below - don't edit by hand. Each file has the per-question",
        "answers, retrieved pages and a breakdown by content type. Answer correctness is an automatic substring",
        "check; page metrics are n/a for Standard mode because it stores no pages.",
        "",
        "| Run | Document | Chunks | Result | Details |",
        "|---|---|---|---|---|",
    ]
    for name, title in ROWS:
        path = RESULTS / name
        if not path.exists():
            continue
        s = summarize(path)
        lines.append(f"| {title} | `{s['document']}` | {s['chunks']} | {s['headline']} | [{name}]({name}) |")
    lines += [
        "",
        "How to read the comparisons: on the plain-prose GPO report Standard answers every question the Report mode",
        "does (the same 15/15) - what Report adds there is page-tagged sources and clean refusals, which this",
        "substring check does not score. On the iMac report, where facts sit in tables, charts and footnotes, Standard",
        "misses 2 of 21 that Visual answers. The 15-21 question sets are small, so treat these as a sanity check, not a benchmark.",
        "",
        "Standard mode was not run on the 200-page World Bank report: chunking it the Standard way means ~1,100",
        "embedding calls, more than the free Gemini tier allows in a day alongside the other runs.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    (RESULTS / "README.md").write_text(build())
    print(f"wrote {RESULTS / 'README.md'}")
